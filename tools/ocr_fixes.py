"""The OCR pipeline's issue dates from the index: each page's issue is dated by the World's
Sunday (sunday_inferred in printings.tsv), not the paper's printing date, so the puzzle's id is
nyw<World date>. Writes the [issue] entries between the markers in fixes/fixes.toml (xword-ocr
docs/fixing.md); run after an intake or a re-dating.

    python tools/ocr_fixes.py
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START, END = "# --- generated by tools/ocr_fixes.py: World dates (do not edit) ---", "# --- end generated ---"


def main() -> None:
    rows = list(csv.DictReader(open(ROOT / "printings.tsv", encoding="utf-8"), delimiter="\t"))
    out = [START, "# The World's Sunday for each issue whose page is dated later (printings.tsv: sunday_inferred,",
           "# with world_no_printed and match). The id of its puzzle is nyw<World date>."]
    seen = set()
    for r in sorted(rows, key=lambda r: (r["paper"], r["date"])):
        if not r["file"] or r["file"].startswith("clip:") or not r["sunday_inferred"]:
            continue
        if r["sunday_inferred"] == r["date"]:
            continue
        ident = f"{r['paper']}-{r['date']}"
        if ident in seen:  # two pages of one issue (a puzzle and its solutions page)
            continue
        seen.add(ident)
        out += ["", f'# No. {r["world_no_printed"] or "?"}: {r["match"]}',
                f'[issue."{ident}"]', f'date = "{r["sunday_inferred"]}"']
    out.append(END)
    path = ROOT / "fixes" / "fixes.toml"
    text = path.read_text(encoding="utf-8")
    if START in text:
        head, rest = text.split(START, 1)
        _, tail = rest.split(END, 1)
        text = head + "\n".join(out) + tail
    else:
        text = text.rstrip("\n") + "\n\n" + "\n".join(out) + "\n"
    path.write_text(text, encoding="utf-8")
    print(f"{path}: {sum(1 for ln in out if ln.startswith('[issue.'))} issues re-dated")


if __name__ == "__main__":
    main()
